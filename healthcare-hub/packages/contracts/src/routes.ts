export function buildOpenApi(version = '0.0.0') {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const r of Object.values(routes)) {
    const full = r.unversioned ? r.path : `/api/v1${r.path}`;
    paths[full] ??= {};
    paths[full][r.method] = {
      summary: r.summary,
      security: r.public ? [] : [{ bearer: [] }],
      parameters: r.public
        ? []
        : [
            {
              name: 'X-Org-Id',
              in: 'header',
              required: false,
              schema: { type: 'string', format: 'uuid' },
            },
          ],
      responses: {
        '200': {
          description: 'OK',
          content: { 'application/json': { schema: z.toJSONSchema(r.response) } },
        },
        default: {
          description: 'Error (RFC 9457 problem+json)',
          content: { 'application/problem+json': { schema: z.toJSONSchema(Problem) } },
        },
      },
    };
  }
  return {
    openapi: '3.1.0',
    info: { title: 'Healthcare Hub API', version },
    components: {
      securitySchemes: { bearer: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' } },
    },
    paths,
  };
}
