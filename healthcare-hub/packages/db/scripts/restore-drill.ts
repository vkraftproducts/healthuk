// Restore drill (NFR-01, UAT-08): dump a database, restore it into a NEW database, prove the copy
// is complete and the audit hash chain intact, and time it against the 4-hour RTO.
//   DRILL_SOURCE_URL=postgresql://postgres:...@host:5432/hub  pnpm --filter @hub/db drill
// Writes a Markdown report (DRILL_REPORT, default ../../docs/compliance/restore-drill-report.md).
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import pg from 'pg';

const source = process.env.DRILL_SOURCE_URL;
if (!source)
  throw new Error('DRILL_SOURCE_URL (a superuser connection to the source database) is required');
const report = process.env.DRILL_REPORT ?? '../../docs/compliance/restore-drill-report.md';
const RTO_MS = 4 * 3_600_000;

const target = `hub_restore_${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}`;
const url = (db: string) => source.replace(/\/[^/?]+(\?|$)/, `/${db}$1`);
const sourceDb = new URL(source).pathname.slice(1);

async function q<T = Record<string, unknown>>(conn: string, text: string): Promise<T[]> {
  const c = new pg.Client({ connectionString: conn });
  await c.connect();
  try {
    return (await c.query(text)).rows as T[];
  } finally {
    await c.end();
  }
}
async function counts(conn: string): Promise<Record<string, number>> {
  const c = new pg.Client({ connectionString: conn });
  await c.connect();
  try {
    const out: Record<string, number> = {};
    const tables = await c.query(
      `SELECT tablename AS t FROM pg_tables WHERE schemaname = 'public' ORDER BY 1`,
    );
    for (const { t } of tables.rows as { t: string }[])
      out[t] = Number((await c.query(`SELECT count(*) AS n FROM "${t}"`)).rows[0].n);
    return out;
  } finally {
    await c.end();
  }
}

const started = Date.now();
const dir = mkdtempSync(join(tmpdir(), 'hub-drill-'));
const file = join(dir, 'hub.dump');
console.log(`1/4 dump ${sourceDb}`);
execFileSync('pg_dump', ['--format=custom', '--file', file, source], { stdio: 'inherit' });
const dumped = Date.now();
console.log(`2/4 restore into new database ${target}`);
await q(url('postgres'), `CREATE DATABASE ${target}`);
execFileSync('pg_restore', ['--exit-on-error', '--dbname', url(target), file], {
  stdio: 'inherit',
});
const restored = Date.now();
console.log('3/4 verify row counts and audit chains');
const a = await counts(source);
const b = await counts(url(target));
const mismatched = Object.keys(a).filter((t) => a[t] !== b[t]);
const orgs = await q<{ id: string; name: string }>(
  url(target),
  'SELECT id, name FROM organisation ORDER BY name',
);
const chains: { name: string; broken: string | null }[] = [];
for (const o of orgs) {
  const r = await q<{ broken_seq: string; reason: string }>(
    url(target),
    `SELECT broken_seq::text, reason FROM audit_verify_chain('${o.id}'::uuid)`,
  );
  chains.push({ name: o.name, broken: r[0] ? `${r[0].broken_seq} (${r[0].reason})` : null });
}
const verified = Date.now();
const ok =
  mismatched.length === 0 && chains.every((c) => c.broken === null) && verified - started < RTO_MS;
console.log(`4/4 ${ok ? 'PASS' : 'FAIL'} in ${((verified - started) / 1000).toFixed(1)} s`);

const total = Object.values(b).reduce((s, n) => s + n, 0);
const lines = [
  '# Restore drill report',
  '',
  `**Result: ${ok ? 'PASS' : 'FAIL'}** · ${new Date(started).toISOString()} · generated by \`packages/db/scripts/restore-drill.ts\``,
  '',
  '| Step | Time |',
  '| --- | --- |',
  `| Dump (\`pg_dump --format=custom\`, ${(statSync(file).size / 1024 / 1024).toFixed(1)} MB) | ${((dumped - started) / 1000).toFixed(1)} s |`,
  `| Restore into new database \`${target}\` | ${((restored - dumped) / 1000).toFixed(1)} s |`,
  `| Verify | ${((verified - restored) / 1000).toFixed(1)} s |`,
  `| **Total (RTO target 4 h)** | **${((verified - started) / 1000).toFixed(1)} s** |`,
  '',
  `- Tables compared: ${Object.keys(a).length}; rows restored: ${total}; mismatched tables: ${mismatched.length ? mismatched.join(', ') : 'none'}.`,
  `- Audit hash chains verified on the restored copy: ${chains.map((c) => `${c.name} ${c.broken === null ? 'intact' : `BROKEN at ${c.broken}`}`).join('; ')}.`,
  '',
  '## Scope of this run',
  '',
  process.env.DRILL_CONTEXT ??
    'Local drill on the build machine (synthetic data). It proves the dump/restore procedure and the verification steps; the production drill restores an Azure point-in-time backup to a new server (docs/runbooks/restore.md) and records its own report.',
  '',
];
writeFileSync(report, lines.join('\n'));
rmSync(dir, { recursive: true, force: true });
if (process.env.DRILL_KEEP !== '1') await q(url('postgres'), `DROP DATABASE ${target}`);
if (!ok) process.exit(1);
